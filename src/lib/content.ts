import { type CyberNode, type Workflow } from './model';
function node(
  id: string,
  title: string,
  op: CyberNode['op'],
  description: string,
  detail: string,
  x: number,
  y: number,
  requires: string[] = [],
  produces: string[] = [],
): CyberNode {
  return {
    id,
    title,
    op,
    description,
    detail,
    position: { x, y },
    requires,
    produces,
    timeoutMs: 5000,
    retries: 1,
  };
}
function edge(source: string, target: string, when: 'always' | 'yes' | 'no' = 'always') {
  return { id: `${source}-${target}`, source, target, when };
}
